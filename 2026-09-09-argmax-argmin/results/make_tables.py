#!/usr/bin/env python3
"""Regenerate tables.md from the raw criterion text outputs in results/.

Parses `results/bench_{arg,anchors}_{portable,native}.txt` (criterion's
human-readable report, tee'd by reproduce.sh) and emits markdown tables with
median times and derived GB/s (bytes = n * 8 for f64, n * 4 for f32; arg*
reads the input once, writes nothing).
"""

import re
from pathlib import Path

HERE = Path(__file__).parent

TIME_RE = re.compile(r"time:\s+\[([0-9.]+)\s*(ns|µs|ms)\s+([0-9.]+)\s*(ns|µs|ms)\s+([0-9.]+)\s*(ns|µs|ms)\]")
UNIT = {"ns": 1e-9, "µs": 1e-6, "ms": 1e-3}


def parse(path: Path) -> dict:
    """Return {bench_id (e.g. 'arg_1d/small_64-serial_f64/argmax'): median_seconds}."""
    out = {}
    if not path.exists():
        return out
    pending_name = None
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line.startswith(("arg_", "anchor_ndarray_arg/")) and " " not in line:
            pending_name = line
            continue
        m = TIME_RE.search(line)
        if m and pending_name:
            out[pending_name] = float(m.group(3)) * UNIT[m.group(4)]
            pending_name = None
    return out


def fmt(t: float) -> str:
    if t >= 1e-3:
        return f"{t * 1e3:.2f} ms"
    if t >= 1e-6:
        return f"{t * 1e6:.2f} µs"
    return f"{t * 1e9:.1f} ns"


def find_rstsr(d: dict, bench_group: str, label: str, op: str, dev: str, dt: str) -> float | None:
    """Match e.g. key 'arg_1d/medium_1000000-serial_f64' with last part == op."""
    for k, v in d.items():
        parts = k.split("/")
        if len(parts) != 3 or parts[0] != bench_group or parts[2] != op:
            continue
        mid = parts[1]
        if mid.startswith(f"{label}-") and mid.endswith(f"-{dev}_{dt}"):
            return v
    return None


def find_anchor(d: dict, bench_id_prefix: str, op: str) -> float | None:
    for k, v in d.items():
        parts = k.split("/")
        if len(parts) != 3 or parts[0] != "anchor_ndarray_arg" or parts[2] != op:
            continue
        if parts[1] == bench_id_prefix:
            return v
    return None


def main() -> None:
    port = parse(HERE / "bench_arg_portable.txt")
    nat = parse(HERE / "bench_arg_native.txt")
    port_a = parse(HERE / "bench_anchors_portable.txt")
    nat_a = parse(HERE / "bench_anchors_native.txt")

    lines = [
        "# T6 argmax/argmin — baseline tables (regenerable)",
        "",
        "Generated by `make_tables.py` from the raw criterion outputs",
        "(`bench_arg_*.txt`, `bench_anchors_*.txt`). GB/s = bytes-read / time;",
        "the large class (80 MB for 1-D 1e7 f64, 32 MB for 2048x2048 f64) is",
        "partially L3-assisted on this 128 MiB X3D machine — the honest DRAM",
        "ceiling is T0's triad ≈ 40 GB/s serial. Times are criterion medians",
        "(100 samples).",
        "",
        "## 1-D argmax/argmin (rstsr), median time and GB/s",
        "",
        "| case | serial portable | GB/s | serial native | GB/s | faer16 portable | GB/s | faer16 native | GB/s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    cases_1d = [
        ("small", 64, "f64"),
        ("small_odd", 1000, "f64"),
        ("medium", 1_000_000, "f64"),
        ("large", 10_000_000, "f64"),
        ("large", 10_000_000, "f32"),
    ]
    for label, n, dt in cases_1d:
        for op in ("argmax", "argmin"):
            row = [f"| {label}_{n} {dt} {op}"]
            for dev in ("serial", "faer16"):
                for d in (port, nat):
                    v = find_rstsr(d, "arg_1d", f"{label}_{n}", op, dev, dt)
                    row.append(f"| {fmt(v)} " if v else "| - ")
                    row.append(f"| {n * (8 if dt == 'f64' else 4) / v / 1e9:.1f} " if v else "| - ")
            lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## 2-D whole-tensor argmax/argmin (rstsr, flat row-major index)",
        "",
        "| case | serial portable | GB/s | serial native | GB/s | faer16 portable | GB/s | faer16 native | GB/s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for label, m, n in [("small", 64, 64), ("medium", 512, 512), ("large", 2048, 2048)]:
        for op in ("argmax", "argmin"):
            row = [f"| {label}_{m}x{n} f64 {op}"]
            for dev in ("serial", "faer16"):
                for d in (port, nat):
                    v = find_rstsr(d, "arg_2d_whole", f"{label}_{m}x{n}", op, dev, "f64")
                    row.append(f"| {fmt(v)} " if v else "| - ")
                    row.append(f"| {m * n * 8 / v / 1e9:.1f} " if v else "| - ")
            lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## Strided case: transpose view a.t() (non-contiguous fallback path)",
        "",
        "| case | serial portable | serial native | faer16 portable | faer16 native |",
        "|---|---|---|---|---|",
    ]
    for label, m, n in [("small", 64, 64), ("large", 2048, 2048)]:
        for op in ("argmax", "argmin"):
            row = [f"| {label}_{n}x{m}-tview f64 {op}"]
            for dev in ("serial", "faer16"):
                for d in (port, nat):
                    v = find_rstsr(d, "arg_strided", f"{label}_{n}x{m}-tview", op, dev, "f64")
                    row.append(f"| {fmt(v)} " if v else "| - ")
            lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## ndarray-stats anchors (single-threaded)",
        "",
        "| case | argmax portable | argmax native | argmin portable | argmin native |",
        "|---|---|---|---|---|",
    ]
    for prefix, note in [
        ("small_64-f64", ""),
        ("small_odd_1000-f64", ""),
        ("medium_1000000-f64", ""),
        ("large_10000000-f64", ""),
        ("large_10000000-f32", " (f32)"),
        ("small_64x64-f64", " (2-D whole)"),
        ("medium_512x512-f64", " (2-D whole)"),
        ("large_2048x2048-f64", " (2-D whole)"),
        ("large_2048x2048-tview-f64", " (2-D t-view)"),
    ]:
        row = [f"| {prefix.split('-')[0]}{note} "]
        for op in ("argmax", "argmin"):
            for d in (port_a, nat_a):
                v = find_anchor(d, prefix, op)
                row.append(f"| {fmt(v)} " if v else "| - ")
        lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## perf stat -d, argmax/argmin 1e7 f64 serial (native), 150 iterations = 1.5e9 elements",
        "## (argmax_1e6: 800 iterations = 8e8 elements); GB/s = bytes / task-clock",
        "",
        "| op | ms/iter | GB/s | ins/elem | cyc/elem | IPC | L1d-miss% |",
        "|---|---|---|---|---|---|---|",
    ]

    def perf_row(fname: str, iters: int, n: int) -> str:
        pf = HERE / "perf" / fname
        if not pf.exists():
            return f"| {fname} | (missing) | | | | | |"
        txt = pf.read_text()

        def grab(pat: str) -> float:
            m = re.search(pat, txt)
            return float(m.group(1).replace(",", "")) if m else float("nan")

        total_ms = grab(r"([\d,\.]+)\s+msec task-clock")
        cycles = grab(r"([\d,]+)\s+cpu-cycles")
        ins = grab(r"([\d,]+)\s+instructions\s+#")
        l1m_pct = grab(r"([\d\.]+)\s+%\s+l1d_miss_rate")
        elem = iters * n
        gb = n * 8 * iters / (total_ms * 1e-3) / 1e9
        name = fname.removeprefix("perf_").removesuffix(".txt")
        return (
            f"| {name} | {total_ms / iters:.2f} | {gb:.2f} "
            f"| {ins / elem:.1f} | {cycles / elem:.1f} | {ins / cycles:.2f} | {l1m_pct} |"
        )

    lines.append(perf_row("perf_argmax.txt", 150, 10_000_000))
    lines.append(perf_row("perf_argmin.txt", 150, 10_000_000))
    lines.append(perf_row("perf_argmax_1e6.txt", 800, 1_000_000))

    # ------------------------- candidate (phase 2 patch) -------------------------
    cand = parse(HERE / "candidate" / "bench_arg_portable.txt")
    cand_n = parse(HERE / "candidate" / "bench_arg_native.txt")

    lines += [
        "",
        "# Candidate (phase 2): contiguous 8-lane fast path, patched 386948be",
        "",
        "## 1-D argmax/argmin, candidate vs baseline (x = speedup)",
        "",
        "| case | serial portable | x | serial native | x | faer16 portable | x | faer16 native | x |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    def rstsr_pair(base: dict, candd: dict, bench_group: str, prefix: str, op: str, dev: str, dt: str):
        b = find_rstsr(base, bench_group, prefix, op, dev, dt)
        c = find_rstsr(candd, bench_group, prefix, op, dev, dt)
        return b, c

    for label, n, dt in cases_1d:
        for op in ("argmax", "argmin"):
            row = [f"| {label}_{n} {dt} {op} "]
            for dev in ("serial", "faer16"):
                for base, candd in ((port, cand), (nat, cand_n)):
                    b, c = rstsr_pair(base, candd, "arg_1d", f"{label}_{n}", op, dev, dt)
                    if b and c:
                        row.append(f"| {fmt(c)} ({b / c:.1f}x) ")
                    else:
                        row.append("| - ")
            lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## 2-D whole-tensor + strided t-view, candidate vs baseline (x = speedup; gates: <=3% = ok)",
        "",
        "| case | serial portable | x | serial native | x | faer16 portable | x | faer16 native | x |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for label, m, n in [("small", 64, 64), ("medium", 512, 512), ("large", 2048, 2048)]:
        for op in ("argmax", "argmin"):
            row = [f"| whole {label}_{m}x{n} {op} "]
            for dev in ("serial", "faer16"):
                for base, candd in ((port, cand), (nat, cand_n)):
                    b = find_rstsr(base, "arg_2d_whole", f"{label}_{m}x{n}", op, dev, "f64")
                    c = find_rstsr(candd, "arg_2d_whole", f"{label}_{m}x{n}", op, dev, "f64")
                    row.append(f"| {fmt(c)} ({b / c:.1f}x) " if b and c else "| - ")
            lines.append(" ".join(row) + "|")
    for label, m, n in [("small", 64, 64), ("large", 2048, 2048)]:
        for op in ("argmax", "argmin"):
            row = [f"| tview {label}_{n}x{m} {op} "]
            for dev in ("serial", "faer16"):
                for base, candd in ((port, cand), (nat, cand_n)):
                    b = find_rstsr(base, "arg_strided", f"{label}_{n}x{m}-tview", op, dev, "f64")
                    c = find_rstsr(candd, "arg_strided", f"{label}_{n}x{m}-tview", op, dev, "f64")
                    row.append(f"| {fmt(c)} ({(c / b - 1) * 100:+.1f}%) " if b and c else "| - ")
            lines.append(" ".join(row) + "|")

    lines += [
        "",
        "## perf stat -d candidate (argmax/argmin 1e7 f64 serial native, 150 iters; argmax_1e6: 800 iters)",
        "",
        "| op | ms/iter | GB/s | ins/elem | cyc/elem | IPC | L1d-miss% |",
        "|---|---|---|---|---|---|---|",
    ]
    lines.append(perf_row("perf_argmax_candidate.txt", 150, 10_000_000))
    lines.append(perf_row("perf_argmin_candidate.txt", 150, 10_000_000))
    lines.append(perf_row("perf_argmax_1e6_candidate.txt", 800, 1_000_000))

    (HERE / "tables.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {HERE / 'tables.md'}")


if __name__ == "__main__":
    main()
