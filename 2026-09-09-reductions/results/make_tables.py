#!/usr/bin/env python3
"""Regenerate results/tables.md from criterion outputs (phase-1 baseline).

Mean point estimate from new/estimates.json (same convention as T7; median
differs by <1% and changes no conclusion). Phase 2 will extend this to
compare `candidate` vs the committed `portable`/`native` baselines.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load(crit_home, group):
    root = os.path.join(HERE, crit_home, group)
    out = {}
    if not os.path.isdir(root):
        return out
    for dirpath, _dirnames, filenames in os.walk(root):
        if "new" not in _dirnames:
            continue
        est = os.path.join(dirpath, "new", "estimates.json")
        if os.path.isfile(est):
            case = os.path.relpath(dirpath, root)  # e.g. large_...-serial_f64/sum_axis0
            with open(est) as f:
                out[case] = json.load(f)["mean"]["point_estimate"]
    return out


def main():
    lines = []
    lines.append("# T2' phase-1 baseline tables (criterion mean point estimates)\n")
    lines.append("Regenerated by `python3 results/make_tables.py` from\n"
                 "`results/criterion_{portable,native}/`. GB/s = input bytes / mean time\n"
                 "(L3-assisted above the ~40 GB/s DRAM triad ceiling per T0 caveat).\n")

    # 2-D groups
    for group in ["reduce2d", "reduce2d_f32", "reduce1d"]:
        for cfg in ["portable", "native"]:
            data = load(f"criterion_{cfg}", group)
            if not data:
                continue
            lines.append(f"\n## {group} — {cfg}\n")
            lines.append("| case | mean | GB/s |")
            lines.append("|---|---|---|")
            for case in sorted(data):
                ns = data[case]
                # elements from the case label: last `<a>x<b>` or `_1e7`
                elems = 0.0
                for part in case.split("-")[0].split("_")[1:]:
                    if "x" in part:
                        a, b = part.split("x")
                        elems = float(a) * float(b)
                    elif part.endswith("e7"):
                        elems = float(part.replace("e7", "")) * 1e7
                gbs = elems * 8.0 / ns if ns else 0.0
                lines.append(f"| {case} | {ns/1e6:.4f} ms | {gbs:.1f} |")

    # anchors
    for cfg in ["portable", "native"]:
        data = load(f"criterion_{cfg}", "anchors_ndarray")
        if not data:
            continue
        lines.append(f"\n## anchors_ndarray — {cfg}\n")
        lines.append("| case | mean | GB/s |")
        lines.append("|---|---|---|")
        for case in sorted(data):
            ns = data[case]
            elems = 0.0
            for part in case.split("-")[0].split("_")[1:]:
                if "x" in part:
                    a, b = part.split("x")
                    elems = float(a) * float(b)
                elif part.endswith("e7"):
                    elems = float(part.replace("e7", "")) * 1e7
            gbs = elems * 8.0 / ns if ns else 0.0
            lines.append(f"| {case} | {ns/1e6:.4f} ms | {gbs:.1f} |")

    with open(os.path.join(HERE, "tables.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.join(HERE, 'tables.md')}")


if __name__ == "__main__":
    main()
