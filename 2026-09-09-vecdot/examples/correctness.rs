//! Correctness gate for T3' phase 1 (campaign plan §3.2: correctness before
//! any perf claim).
//!
//! Compares rt::vecdot and 1-D `%` (inner_dot) against naive scalar loops and
//! against ndarray anchors, on deterministic fixtures, covering:
//! - 1-D dot: f64 / f32 / Complex<f64>, odd sizes, NaN poisoning.
//! - Batched axis -1 (branch: contiguous-summed), f64 + Complex<f64>, odd
//!   size 1000x777.
//! - Batched axis 0 (branch: contiguous-remaining, MaybeUninit RMW).
//! - Strided b (general branch), f-contiguous a, zero-stride broadcast of
//!   BOTH a remaining axis and a summed axis.
//! - inner_dot `%`: contiguous + strided (row view) + NaN, f64 + Complex.
//! - Both devices: DeviceCpuSerial and DeviceFaer (16 threads).
//!
//! NaN semantics (documented at 386948be, must be preserved): vecdot and
//! inner_dot have NO NaN filtering — plain IEEE poisoning through `+`/`*`;
//! any NaN in a contracted pair makes that output NaN. (Unlike
//! argmin/argmax, there is no skip logic anywhere in the chain.)
//!
//! Device code is generated by a macro (not a generic fn) so each rstsr call
//! site inherits its own trait bounds — the T0 harness convention.

use exp_vecdot::{assert_faer_threads, gen_value};
use num::Complex;
use rstsr_core::prelude::*;

use std::sync::atomic::{AtomicUsize, Ordering};

static FAILS: AtomicUsize = AtomicUsize::new(0);
static TOTAL: AtomicUsize = AtomicUsize::new(0);

fn check(name: &str, cond: bool) {
    TOTAL.fetch_add(1, Ordering::Relaxed);
    if !cond {
        FAILS.fetch_add(1, Ordering::Relaxed);
        println!("FAIL: {name}");
    }
}

fn check_closev(name: &str, a: &[f64], b: &[f64]) {
    let ok = a.len() == b.len()
        && a.iter().zip(b).all(|(x, y)| (x - y).abs() <= 1e-9 * (1.0 + x.abs() + y.abs()));
    check(name, ok);
}

fn check_closev_c(name: &str, a: &[Complex<f64>], b: &[Complex<f64>]) {
    let ok = a.len() == b.len()
        && a.iter().zip(b).all(|(x, y)| {
            (x.re - y.re).abs() <= 1e-9 * (1.0 + x.re.abs() + y.re.abs())
                && (x.im - y.im).abs() <= 1e-9 * (1.0 + x.im.abs() + y.im.abs())
        });
    check(name, ok);
}

fn naive_dot(a: &[f64], b: &[f64]) -> f64 {
    a.iter().zip(b).map(|(x, y)| x * y).sum()
}

fn naive_dot_c(a: &[Complex<f64>], b: &[Complex<f64>]) -> Complex<f64> {
    a.iter().zip(b).map(|(x, y)| x.conj() * y).sum()
}

fn naive_batched_am1(a: &[f64], b: &[f64], m: usize, n: usize) -> Vec<f64> {
    (0..m).map(|i| naive_dot(&a[i * n..(i + 1) * n], &b[i * n..(i + 1) * n])).collect()
}

fn naive_batched_am1_c(a: &[Complex<f64>], b: &[Complex<f64>], m: usize, n: usize) -> Vec<Complex<f64>> {
    (0..m).map(|i| naive_dot_c(&a[i * n..(i + 1) * n], &b[i * n..(i + 1) * n])).collect()
}

fn naive_batched_axis0(a: &[f64], b: &[f64], m: usize, n: usize) -> Vec<f64> {
    (0..n).map(|j| (0..m).map(|i| a[i * n + j] * b[i * n + j]).sum()).collect()
}

macro_rules! run_device {
    ($dev:expr, $dev_name:expr) => {{
        let dev = $dev;
        let tag = |s: &str| format!("{s}-{}", $dev_name);

        // ------------------------------------------------------------------
        // 1-D dot: f64 (odd size), f32, Complex
        // ------------------------------------------------------------------
        let n = 777;
        let av: Vec<f64> = (0..n).map(|i| gen_value(i, 1)).collect();
        let bv: Vec<f64> = (0..n).map(|i| gen_value(i, 2)).collect();
        let a = rt::asarray((av.clone(), [n], dev));
        let b = rt::asarray((bv.clone(), [n], dev));
        let c = rt::vecdot(&a, &b, None).reshape(-1).to_vec();
        // NOTE: 8-lane unrolled summation re-associates the fold, so only
        // relative-tolerance comparison is valid for multi-element dots
        // (serial inner_dot folds sequentially and IS bit-exact — locked
        // separately below).
        check_closev(&tag("dot1d-f64-odd"), &c, &[naive_dot(&av, &bv)]);

        let av32: Vec<f32> = (0..n).map(|i| gen_value(i, 1) as f32).collect();
        let bv32: Vec<f32> = (0..n).map(|i| gen_value(i, 2) as f32).collect();
        let a32 = rt::asarray((av32.clone(), [n], dev));
        let b32 = rt::asarray((bv32.clone(), [n], dev));
        let c32 = rt::vecdot(&a32, &b32, None).reshape(-1).to_vec();
        let expect32: f32 = av32.iter().zip(&bv32).map(|(x, y)| x * y).sum();
        check(&tag("dot1d-f32-odd"), (c32[0] - expect32).abs() <= 1e-3 * expect32.abs());

        let avc: Vec<Complex<f64>> = (0..n).map(|i| Complex::new(gen_value(i, 1), gen_value(i, 31))).collect();
        let bvc: Vec<Complex<f64>> = (0..n).map(|i| Complex::new(gen_value(i, 2), gen_value(i, 32))).collect();
        let ac = rt::asarray((avc.clone(), [n], dev));
        let bc = rt::asarray((bvc.clone(), [n], dev));
        let cc = rt::vecdot(&ac, &bc, None).reshape(-1).to_vec();
        check_closev_c(&tag("dot1d-c64-odd"), &cc, &[naive_dot_c(&avc, &bvc)]);

        // NaN poisoning: NaN in a -> NaN out; NaN in b -> NaN out.
        let mut avn = av.clone();
        avn[100] = f64::NAN;
        let an = rt::asarray((avn, [n], dev));
        let cn = rt::vecdot(&an, &b, None).reshape(-1).to_vec();
        check(&tag("dot1d-nan-in-a"), cn[0].is_nan());
        let mut bvn = bv.clone();
        bvn[200] = f64::NAN;
        let bn = rt::asarray((bvn, [n], dev));
        let cn2 = rt::vecdot(&a, &bn, None).reshape(-1).to_vec();
        check(&tag("dot1d-nan-in-b"), cn2[0].is_nan());

        // ------------------------------------------------------------------
        // Batched axis -1 (contiguous-summed branch), f64 + c64, odd size
        // ------------------------------------------------------------------
        let (m, k) = (1000usize, 777usize);
        let ma: Vec<f64> = (0..m * k).map(|i| gen_value(i, 11)).collect();
        let mb: Vec<f64> = (0..m * k).map(|i| gen_value(i, 12)).collect();
        let ta = rt::asarray((ma.clone(), [m, k], dev));
        let tb = rt::asarray((mb.clone(), [m, k], dev));
        let tc = rt::vecdot(&ta, &tb, None).reshape(-1).to_vec();
        check_closev(&tag("batched-am1-f64-1000x777"), &tc, &naive_batched_am1(&ma, &mb, m, k));

        let mac: Vec<Complex<f64>> = (0..m * k).map(|i| Complex::new(gen_value(i, 11), gen_value(i, 41))).collect();
        let mbc: Vec<Complex<f64>> = (0..m * k).map(|i| Complex::new(gen_value(i, 12), gen_value(i, 42))).collect();
        let tac = rt::asarray((mac.clone(), [m, k], dev));
        let tbc = rt::asarray((mbc.clone(), [m, k], dev));
        let tcc = rt::vecdot(&tac, &tbc, None).reshape(-1).to_vec();
        check_closev_c(&tag("batched-am1-c64"), &tcc, &naive_batched_am1_c(&mac, &mbc, m, k));

        // NaN in one row poisons exactly that row.
        let mut man = ma.clone();
        man[5 * k + 3] = f64::NAN;
        let tan = rt::asarray((man, [m, k], dev));
        let tcn = rt::vecdot(&tan, &tb, None).reshape(-1).to_vec();
        check(&tag("batched-am1-nan-row5"), tcn[5].is_nan() && (0..m).filter(|&i| i != 5).all(|i| !tcn[i].is_nan()));

        // ------------------------------------------------------------------
        // Batched axis 0 (contiguous-remaining / RMW branch)
        // ------------------------------------------------------------------
        let tc0 = rt::vecdot(&ta, &tb, 0).reshape(-1).to_vec();
        check_closev(&tag("batched-axis0-f64-1000x777"), &tc0, &naive_batched_axis0(&ma, &mb, m, k));

        // axis-0 with the contiguous remaining run ABOVE the 32 KiB local-
        // accumulator budget (20000 f64 = 160 KiB): exercises the preserved
        // fall-through band path of the phase-2 kernel.
        let (m2, k2) = (8usize, 20000usize);
        let ma2: Vec<f64> = (0..m2 * k2).map(|i| gen_value(i, 21)).collect();
        let mb2: Vec<f64> = (0..m2 * k2).map(|i| gen_value(i, 22)).collect();
        let ta2 = rt::asarray((ma2.clone(), [m2, k2], dev));
        let tb2 = rt::asarray((mb2.clone(), [m2, k2], dev));
        let tc2 = rt::vecdot(&ta2, &tb2, 0).reshape(-1).to_vec();
        check_closev(&tag("batched-axis0-f64-largefallthrough"), &tc2, &naive_batched_axis0(&ma2, &mb2, m2, k2));

        // 3-D batched ax-1 (multi-dim remaining): branch-1 flat-path
        // fall-through must keep the dispatch machinery results.
        let (d0, d1_, d2_) = (2usize, 3usize, 4usize);
        let m3: Vec<f64> = (0..d0 * d1_ * d2_).map(|i| gen_value(i, 23)).collect();
        let n3v: Vec<f64> = (0..d0 * d1_ * d2_).map(|i| gen_value(i, 24)).collect();
        let t3a = rt::asarray((m3.clone(), [d0, d1_, d2_], dev));
        let t3b = rt::asarray((n3v.clone(), [d0, d1_, d2_], dev));
        let t3c = rt::vecdot(&t3a, &t3b, None).reshape(-1).to_vec();
        let t3_expect: Vec<f64> = (0..d0 * d1_)
            .map(|r| naive_dot(&m3[r * d2_..(r + 1) * d2_], &n3v[r * d2_..(r + 1) * d2_]))
            .collect();
        check_closev(&tag("batched-3d-ax1-fallthrough"), &t3c, &t3_expect);

        // ------------------------------------------------------------------
        // Strided b (general branch): b stored (k, m), viewed transposed.
        // View semantics: view[i,j] = mb[i + j*m], so
        // expected[i] = sum_j ma[i*k+j] * mb[i + j*m].
        // ------------------------------------------------------------------
        let tbst = rt::asarray((mb.clone(), [k, m], dev));
        let tbv = tbst.t(); // (m, k) strides (1, m)
        let tcs = rt::vecdot(&ta, &tbv, None).reshape(-1).to_vec();
        let expect_s: Vec<f64> = (0..m)
            .map(|i| (0..k).map(|j| ma[i * k + j] * mb[i + j * m]).sum::<f64>())
            .collect();
        check_closev(&tag("batched-strided-f64"), &tcs, &expect_s);

        // f-contiguous a: same math through the f-contig (col-major) layout
        let taf = ta.to_contig(ColMajor);
        let tcf = rt::vecdot(&taf, &tb, None).reshape(-1).to_vec();
        check_closev(&tag("batched-am1-fa-fcontig"), &tcf, &naive_batched_am1(&ma, &mb, m, k));

        // ------------------------------------------------------------------
        // Broadcast (zero-stride) cases
        // ------------------------------------------------------------------
        // (1) 2-D . 1-D: b's remaining part broadcasts (stride-0 remaining).
        let tv = rt::asarray((bv.clone(), [k], dev));
        let tcb = rt::vecdot(&ta, &tv, None).reshape(-1).to_vec();
        let expect: Vec<f64> = (0..m).map(|i| naive_dot(&ma[i * k..(i + 1) * k], &bv)).collect();
        check_closev(&tag("batched-am1-broadcast-1db"), &tcb, &expect);

        // (2) explicit broadcast_to view of the remaining axis
        //     ([1,k] data broadcast to [m,k]: remaining dim m has stride 0)
        let tvr = tv.broadcast_to(vec![m, k]);
        let tcb2 = rt::vecdot(&ta, &tvr, None).reshape(-1).to_vec();
        check_closev(&tag("batched-am1-broadcast-rem"), &tcb2, &expect);

        // (3) stride-0 SUMMED axis: b is (m,1) broadcast to (m,k) — b[i,j]=v[i]
        //     independent of j; the contracted axis has stride 0.
        //     expected[i] = v[i] * rowsum(a[i, :]).
        let v: Vec<f64> = (0..m).map(|i| gen_value(i, 14)).collect();
        let tb2 = rt::asarray((v.clone(), [m, 1], dev));
        let tb2b = tb2.broadcast_to(vec![m, k]);
        let tcb4 = rt::vecdot(&ta, &tb2b, None).reshape(-1).to_vec();
        let expect4: Vec<f64> =
            (0..m).map(|i| v[i] * (0..k).map(|j| ma[i * k + j]).sum::<f64>()).collect();
        check_closev(&tag("batched-am1-broadcast-summedaxis"), &tcb4, &expect4);

        // ------------------------------------------------------------------
        // inner_dot: `%` on 1-D . 1-D
        // ------------------------------------------------------------------
        // PHASE-2 NOTE (pre-declared in PLAN.md §2 Option B, G1-reviewed):
        // the serial kernel now takes an 8-lane contiguous fast path when
        // both strides are 1 and alpha==1 && beta==0 — the fold is
        // re-associated, so the former bit-exact serial lock is now
        // tolerance-based everywhere. (faer16 always re-associated via its
        // rayon fold; there was never a cross-device bit-exact contract.)
        let d1 = &a % &b;
        check_closev(&tag("innerdot-f64-contig"), &d1.reshape(-1).to_vec(), &[naive_dot(&av, &bv)]);

        // fast-path/fallback boundaries of the phase-2 kernels:
        // n=300 < PARALLEL_SWITCH(512): faer16 sequential fallback;
        // n=777 contiguous: faer16 chunked fold; row views: strided fallback.
        let n3 = 300;
        let a3 = rt::asarray((av[..n3].to_vec(), [n3], dev));
        let b3 = rt::asarray((bv[..n3].to_vec(), [n3], dev));
        let d3 = &a3 % &b3;
        check_closev(
            &tag("innerdot-f64-n300-seqfallback"),
            &d3.reshape(-1).to_vec(),
            &[naive_dot(&av[..n3], &bv[..n3])],
        );

        // strided 1-D: row views of a matrix (stride k)
        let row_a = ta.i(3);
        let row_b = tb.i(3);
        let d2 = &row_a % &row_b;
        check_closev(
            &tag("innerdot-f64-strided-rowview"),
            &d2.reshape(-1).to_vec(),
            &[naive_dot(&ma[3 * k..4 * k], &mb[3 * k..4 * k])],
        );

        // complex inner dot (NO conjugation for `%` — plain a*b sum)
        let dc = &ac % &bc;
        let expect_c: Complex<f64> = avc.iter().zip(&bvc).map(|(x, y)| x * y).sum();
        check_closev_c(&tag("innerdot-c64-no-conj"), &dc.reshape(-1).to_vec(), &[expect_c]);

        // NaN poisoning for inner_dot
        let dn = &an % &b;
        check(&tag("innerdot-nan"), dn.reshape(-1).to_vec()[0].is_nan());

        // small edge: n=1
        let a1 = rt::asarray((vec![2.5_f64], [1], dev));
        let b1 = rt::asarray((vec![-4.0_f64], [1], dev));
        check(&tag("innerdot-n1"), (&a1 % &b1).reshape(-1).to_vec()[0] == -10.0);
        check(&tag("dot1d-n1"), rt::vecdot(&a1, &b1, None).reshape(-1).to_vec()[0] == -10.0);
    }};
}

fn main() {
    let dev_serial = DeviceCpuSerial::default();
    let dev_faer = DeviceFaer::new(0);
    assert_faer_threads(&dev_faer, 16);

    println!("=== correctness: DeviceCpuSerial ===");
    run_device!(&dev_serial, "serial");
    println!("=== correctness: DeviceFaer (16 threads) ===");
    run_device!(&dev_faer, "faer16");

    // ------------------------------------------------------------------
    // ndarray cross-check (f64, batched am1 / axis0 / strided), same data
    // ------------------------------------------------------------------
    use ndarray::Array2;
    let (m, k) = (1000usize, 777usize);
    let ma: Vec<f64> = (0..m * k).map(|i| gen_value(i, 11)).collect();
    let mb: Vec<f64> = (0..m * k).map(|i| gen_value(i, 12)).collect();
    let na = Array2::from_shape_vec((m, k), ma.clone()).unwrap();
    let nb = Array2::from_shape_vec((m, k), mb.clone()).unwrap();
    let nd_am1: Vec<f64> = na.rows().into_iter().zip(nb.rows()).map(|(ra, rb)| ra.dot(&rb)).collect();
    check_closev("ndarray-crosscheck-am1", &nd_am1, &naive_batched_am1(&ma, &mb, m, k));
    let nd_axis0: Vec<f64> = (0..k).map(|j| na.column(j).dot(&nb.column(j))).collect();
    check_closev("ndarray-crosscheck-axis0", &nd_axis0, &naive_batched_axis0(&ma, &mb, m, k));
    // strided: stored (k, m); row i of the (m,k) transposed view = column i
    let nbst = Array2::from_shape_vec((k, m), mb.clone()).unwrap();
    let nd_strided: Vec<f64> =
        (0..m).map(|i| na.row(i).dot(&nbst.column(i))).collect();
    let expect_s: Vec<f64> =
        (0..m).map(|i| (0..k).map(|j| ma[i * k + j] * mb[i + j * m]).sum::<f64>()).collect();
    check_closev("ndarray-crosscheck-strided", &nd_strided, &expect_s);

    let total = TOTAL.load(Ordering::Relaxed);
    let fails = FAILS.load(Ordering::Relaxed);
    println!("\ncorrectness: {total} checks, {fails} failures");
    if fails > 0 {
        std::process::exit(1);
    }
    println!("ALL PASS");
}
